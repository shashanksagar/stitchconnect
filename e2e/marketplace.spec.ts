import { expect, test } from "@playwright/test";
test("landing, capped comparison, keyboard modal and mobile marketplace", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: /Not off the rack/ })).toBeVisible();
  await page.getByRole("link", { name: "Explore the tailors" }).click();
  await expect(page.locator("article")).toHaveCount(5);
  for (const name of ["Amara Atelier", "Luca & Thread", "Studio Meera"]) await page.getByRole("checkbox", { name: `Compare ${name}`, exact: true }).check();
  await page.getByRole("checkbox", { name: "Compare June Studio", exact: true }).click();
  await expect(page.getByText("Compare up to 3 tailors. Remove one to add another.")).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "Compare June Studio", exact: true })).not.toBeChecked();
  await page.getByRole("button", { name: /Compare side by side/ }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog").getByText("$120", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Remove Studio Meera" }).click();
  await expect(page.getByRole("dialog").getByRole("columnheader", { name: /Studio Meera/ })).toHaveCount(0);
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Clear comparison" }).click();
  await page.getByRole("button", { name: "Minimalist", exact: true }).click();
  await expect(page.locator("article")).toHaveCount(2);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "All tailors", exact: true }).click();
  await expect(page.locator("article")).toHaveCount(5);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  for (const img of await page.locator("article img").all()) expect(await img.evaluate((el: HTMLImageElement) => el.complete && el.naturalWidth > 0)).toBe(true);
  await expect(page.locator("article").last()).toHaveCSS("opacity", "1");
  await page.screenshot({ path: test.info().outputPath("marketplace-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await expect(page.locator("article").last()).toHaveCSS("opacity", "1");
  await page.screenshot({ path: test.info().outputPath("landing-desktop.png"), fullPage: true });
  const denied = await page.request.get("/api/orders");
  expect(denied.status()).toBe(401);
});
