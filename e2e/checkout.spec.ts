import { expect, test } from "@playwright/test";
import { address, mutate, png } from "./helpers";
test("customer signup, guided image order, failed payment retry, persistence and private reads", async ({ page, context, browser }) => {
  const email = `browser-${crypto.randomUUID()}@test.local`;
  const invalid = await mutate(context, "/api/signup", { name: "Browser Customer", email, password: "A-test-password-2026", location: "Brooklyn, USA", role: "ADMIN" });
  expect(invalid.status()).toBe(400);
  await page.goto("/signup");
  await page.getByLabel("Your name").fill("Browser Customer");
  await page.getByLabel("City and country").fill("Brooklyn, USA");
  await page.getByLabel("Email address").fill(email);
  await page.getByLabel("Password", { exact: true }).fill("A-test-password-2026");
  await page.getByRole("button", { name: "Create your account" }).click();
  await expect(page).toHaveURL(/\/orders$/);
  expect((await mutate(context, "/api/signup", { name: "Browser Customer", email, password: "A-test-password-2026", location: "Brooklyn, USA" })).status()).toBe(409);
  await page.goto("/order/new/tailor-amara");
  await page.getByLabel("Reference photos").setInputFiles({ name: "inspiration.png", mimeType: "image/png", buffer: png });
  await expect(page.getByAltText("Reference 1")).toBeVisible();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("chest (cm)", { exact: true }).fill("92");
  await page.getByLabel("waist (cm)", { exact: true }).fill("74");
  await page.getByLabel("length (cm)", { exact: true }).fill("110");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  for (const [label, value] of Object.entries({ "Contact name": address.name, "Street address": address.line1, "City / region": address.city, "Postal code": address.postalCode, Country: address.country, "Phone number": address.phone })) await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Create order & continue to demo payment" }).click();
  await expect(page).toHaveURL(/\/orders\/[^/]+$/);
  const id = page.url().split("/").at(-1)!;
  await page.getByRole("button", { name: "Simulate failure" }).click();
  await expect(page.getByRole("status")).toContainText("Demo payment failed");
  await page.getByRole("button", { name: "Pay $60 (demo)", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Demo payment received");
  await page.reload();
  const response = await context.request.get(`/api/orders/${id}`);
  const order = await response.json();
  expect(order.upfrontPaid).toBe(true);
  expect(order.totalAmount).toBe(12000);
  expect(order.measurements.unit).toBe("cm");
  expect(order.referenceImages).toHaveLength(1);
  expect((await context.request.get(order.referenceImages[0])).headers()["content-type"]).toBe("image/png");
  expect((await mutate(context, `/api/orders/${id}/payments`, { installment: "FINAL", outcome: "success" })).status()).toBe(409);
  expect((await context.request.post(`/api/orders/${id}/payments`, { data: { installment: "UPFRONT", outcome: "success" }, headers: { Origin: "https://not-stitch.invalid" } })).status()).toBe(403);
  const outsider = await browser.newContext();
  try {
    expect((await outsider.request.get(`/api/orders/${id}`)).status()).toBe(401);
    expect((await outsider.request.get(order.referenceImages[0])).status()).toBe(401);
  } finally { await outsider.close(); }
  await page.getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL("http://127.0.0.1:3100/");
  await page.getByRole("link", { name: "Log in", exact: true }).click();
  await page.getByLabel("Email address").fill(email);
  await page.getByLabel("Password", { exact: true }).fill("wrong-password");
  await page.getByRole("button", { name: "Welcome back" }).click();
  await expect(page.locator("p[role=alert]")).toContainText("Login failed");
});
